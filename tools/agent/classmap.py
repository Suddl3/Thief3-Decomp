#!/usr/bin/env python3
"""Lead only: find which class each placeholder class is, from evidence in the exe.

    python tools/agent/classmap.py write     # config/<version>/classmap.txt
    python tools/agent/classmap.py stats     # what the map would merge, without writing it

Workers name a class nothing names after the function they match (`Class_<function
address>`), so the methods of one class end up in as many placeholder classes as there are
methods. This tool decides which of them are one class, from the game's code alone:

  - a vtable: a table stored at offset 0 of an object is one class (`Class_<vtable>`, or its
    registered name from classes.txt). Without RTTI the tables sit back to back, so a table
    runs to the next address an instruction names. A function in the slots of one table only
    is that class's; one several tables share belongs to the class whose table the others
    derive from;
  - the tables a function stores at its own `this` (not at an object it makes: a factory
    inlines its product's constructor): it is that class's constructor or destructor. A
    constructor stores its bases' tables before its own, a destructor after; named ones say
    which they are, and give the base edges that read the placeholder-named ones;
  - calls on `this`: a method called with ecx = the caller's own `this` (tracked through
    register moves) belongs to the caller's class or to one of its bases. A method only one
    class's methods call that way is taken to be that class's when the class has no known
    base, which merges the helpers a class calls on itself; this repeats until nothing changes.

A placeholder class whose methods all lead to one class maps to it; one whose methods lead to
several is left alone (its declaration would have to be split by hand). The map lists each
merge with its evidence; tools/agent/restructure.py applies it.
"""

import argparse
import collections
import re
import struct
import sys
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from common import Project, fmt_addr  # noqa: E402

PLACEHOLDER = re.compile(r"^(?:Class|Struct|Object)_[0-9A-Fa-f]{8}$")
WRITES = {3, 4, 5, 6}  # iced OpAccess: write, conditional write, read-write, read-conditional-write
MAP_HEADER = """\
# Which class each placeholder class is: a worker names a class nothing names after the function
# it matched, and these placeholders are the classes of the same game classes. Generated by
# tools/agent/classmap.py from T3Main.exe and src/; tools/agent/restructure.py applies it.
#   <placeholder> <class> <evidence>
"""


class Image:
    """T3Main.exe's sections, and reads of its code and data."""

    def __init__(self, exe: bytes):
        self.exe = exe
        pe = struct.unpack_from("<I", exe, 0x3C)[0]
        count = struct.unpack_from("<H", exe, pe + 6)[0]
        opt = struct.unpack_from("<H", exe, pe + 20)[0]
        base = struct.unpack_from("<I", exe, pe + 24 + 28)[0]
        self.sections = []
        for i in range(count):
            o = pe + 24 + opt + i * 40
            name = exe[o:o + 8].rstrip(b"\0").decode()
            vsize, va, rsize, raw = struct.unpack_from("<IIII", exe, o + 8)
            self.sections.append((name, base + va, min(vsize, rsize), raw))
        self.text = next(s for s in self.sections if s[0] == ".text")
        self.rdata = next(s for s in self.sections if s[0] == ".rdata")

    def offset(self, va: int) -> Optional[int]:
        for _, start, size, raw in self.sections:
            if start <= va < start + size:
                return raw + va - start
        return None

    def dword(self, va: int) -> Optional[int]:
        o = self.offset(va)
        return struct.unpack_from("<I", self.exe, o)[0] if o is not None else None

    def code(self, va: int, size: int) -> bytes:
        o = self.offset(va)
        return self.exe[o:o + size] if o is not None else b""

    def is_code(self, va: int, end: int) -> bool:
        return self.text[1] <= va < end

    def in_rdata(self, va: int) -> bool:
        return self.rdata[1] <= va < self.rdata[1] + self.rdata[2]


def decode(image: Image, start: int, size: int):
    from iced_x86 import Decoder
    return Decoder(32, image.code(start, size), ip=start)


def scan(p: Project, image: Image, functions: Dict[int, int], code_end: int):
    """(stores, tables, marks, calls): each function's vtable stores at offset 0 of its own `this`,
    in order; every table stored at offset 0 of any object (a factory inlines its product's
    constructor: a table, but not the factory's class); every address in .rdata an instruction
    names that holds a code pointer (where one table ends: without RTTI they sit back to back);
    and each function's calls made with ecx holding its `this`."""
    from iced_x86 import InstructionInfoFactory, Mnemonic, OpKind, Register, RegisterExt
    factory = InstructionInfoFactory()
    stores: Dict[int, List[int]] = {}
    tables: Set[int] = set()
    marks: Set[int] = set()
    calls: Dict[int, Set[int]] = collections.defaultdict(set)

    def table_like(value: int) -> bool:
        return image.in_rdata(value) and image.is_code(image.dword(value) or 0, code_end)

    for start in sorted(functions):
        size = functions[start]
        if size <= 0:
            continue
        holders = {Register.ECX}  # the registers holding `this`
        seen = []
        for ins in decode(image, start, size):
            m = ins.mnemonic
            for i in range(ins.op_count):
                if ins.op_kind(i) in (OpKind.IMMEDIATE32, OpKind.IMMEDIATE8TO32) and table_like(ins.immediate(i)):
                    marks.add(ins.immediate(i))
            if ins.memory_displacement and table_like(ins.memory_displacement):
                marks.add(ins.memory_displacement)
            if m == Mnemonic.MOV and ins.op0_kind == OpKind.MEMORY and ins.op1_kind == OpKind.IMMEDIATE32 \
                    and ins.memory_displacement == 0 and ins.memory_index == Register.NONE \
                    and table_like(ins.immediate32):
                tables.add(ins.immediate32)
                if ins.memory_base in holders:
                    seen.append(ins.immediate32)
            if m in (Mnemonic.CALL, Mnemonic.JMP) and ins.op0_kind == OpKind.NEAR_BRANCH32:
                target = ins.near_branch_target
                if Register.ECX in holders and target in functions and target != start:
                    calls[start].add(target)
                if m == Mnemonic.CALL:
                    holders -= {Register.EAX, Register.ECX, Register.EDX}
                continue
            if m == Mnemonic.MOV and ins.op0_kind == OpKind.REGISTER and ins.op1_kind == OpKind.REGISTER:
                dst, src = ins.op0_register, ins.op1_register
                if src in holders:
                    holders.add(dst)
                else:
                    holders.discard(dst)
                continue
            for used in factory.info(ins).used_registers():
                if used.access in WRITES:
                    holders.discard(RegisterExt.full_register32(used.register))
        if seen:
            stores[start] = seen
    return stores, tables, marks, calls


def build(p: Project):
    """The map: {placeholder: (class, evidence)}, and statistics."""
    image = Image(p.exe.read_bytes())
    symbols = [s for s in p.functions if s.size]
    functions = {s.address: s.size for s in symbols}
    names = {s.address: s.name for s in symbols}
    code_end = max(a + s for a, s in functions.items())
    lib_start = p.library_start()
    stores, all_tables, marks, calls = scan(p, image, functions, code_end)

    # vtables and their slots: a table runs to the next address anything names
    tables = sorted(all_tables)
    ends = all_tables | marks
    slots: Dict[int, List[int]] = {}
    for v in tables:
        out, at = [], v
        while True:
            x = image.dword(at)
            if x is None or not image.is_code(x, code_end) or (at != v and at in ends):
                break
            out.append(x)
            at += 4
        slots[v] = out
    in_tables: Dict[int, Set[int]] = collections.defaultdict(set)
    for v, s in slots.items():
        for f in s:
            in_tables[f].add(v)

    # base edges: a constructor stores its bases' tables first, a destructor last. Named
    # constructors and destructors say which they are; a function with a placeholder name and
    # several tables is read by what those say of its tables, else left out.
    bases: Dict[int, Set[int]] = collections.defaultdict(set)   # table -> tables of its bases
    own: Dict[int, int] = {}                                   # function -> the table it is a ctor/dtor of
    unsure = []
    for f, seen in stores.items():
        order = list(dict.fromkeys(seen))
        name = names.get(f, "")
        if len(order) == 1:
            own[f] = order[0]
            continue
        if name.startswith(("??1", "??_G", "??_E")) or "destructor" in name:
            mine, others = order[0], order[1:]
        elif name.startswith("??0"):
            mine, others = order[-1], order[:-1]
        else:
            unsure.append((f, order))
            continue
        own[f] = mine
        for o in others:
            if o != mine:
                bases[mine].add(o)

    def ancestors(v: int) -> Set[int]:
        out, todo = set(), [v]
        while todo:
            for b in bases.get(todo.pop(), ()):
                if b not in out:
                    out.add(b)
                    todo.append(b)
        return out

    for f, order in unsure:
        if all(o in ancestors(order[-1]) for o in order[:-1]):
            own[f] = order[-1]      # stores its bases first: a constructor
        elif all(o in ancestors(order[0]) for o in order[1:]):
            own[f] = order[0]       # its own first: a destructor

    def ancestors(v: int) -> Set[int]:  # noqa: F811 (the same, now with every edge)
        out, todo = set(), [v]
        while todo:
            for b in bases.get(todo.pop(), ()):
                if b not in out:
                    out.add(b)
                    todo.append(b)
        return out

    registered = collections.Counter(c.vtable for c in p.classes().values() if c.vtable)
    reg_name = {c.vtable: c.name for c in p.classes().values() if c.vtable and registered[c.vtable] == 1}

    def class_name(v: int) -> str:
        return reg_name.get(v, f"Class_{v:08X}")

    # each function's class from the tables
    known: Dict[int, Tuple[str, str]] = {}
    for f, vs in in_tables.items():
        if f >= lib_start:
            continue
        if len(vs) == 1:
            v = next(iter(vs))
            known[f] = (class_name(v), f"slot of {fmt_addr(v)}")
            continue
        root = [v for v in vs if all(v == w or v in ancestors(w) for w in vs)]
        if len(root) == 1:
            known[f] = (class_name(root[0]), f"slot of {fmt_addr(root[0])}, inherited by {len(vs) - 1} tables")
    for f, v in own.items():
        if f < lib_start:
            known[f] = (class_name(v), f"stores {fmt_addr(v)}")

    # src: each function's class as defined
    defined: Dict[int, str] = {}
    for address, unit in p.integrated().items():
        sym = p.by_addr.get(address)
        if sym is None:
            continue
        m = re.match(r"^\?\?(?:[0-9]|_[A-Z])([A-Za-z_]\w*)@@|^\?[A-Za-z_]\w*@([A-Za-z_]\w*)@@", sym.name)
        if m:
            defined[address] = m.group(1) or m.group(2)
    for f, cls in defined.items():
        if f not in known and not PLACEHOLDER.match(cls):
            known[f] = (cls, "named")
        elif f not in known and cls in {class_name(v) for v in tables}:
            known[f] = (cls, "vtable class")

    # calls on `this`: a method only one class's methods call that way is that class's, when
    # the class has no base it could belong to instead
    callers: Dict[int, Set[int]] = collections.defaultdict(set)
    for f, targets in calls.items():
        for t in targets:
            callers[t].add(f)
    table_of = {class_name(v): v for v in tables}
    rooted = {n for n, v in table_of.items() if ancestors(v)}
    changed = True
    while changed:
        changed = False
        for g in defined:
            if g in known or g in in_tables:
                continue
            by = {known[c][0] for c in callers.get(g, ()) if c in known}
            if len(by) == 1 and not by & rooted:
                cls = next(iter(by))
                caller = min(c for c in callers[g] if c in known and known[c][0] == cls)
                known[g] = (cls, f"called on this by {fmt_addr(caller)}")
                changed = True

    # placeholders: all their methods must lead to one class
    methods: Dict[str, List[int]] = collections.defaultdict(list)
    for f, cls in defined.items():
        methods[cls].append(f)
    mapping: Dict[str, Tuple[str, str]] = {}
    split = []
    for cls, fs in sorted(methods.items()):
        if not PLACEHOLDER.match(cls):
            continue
        leads = {known[f][0] for f in fs if f in known}
        if len(leads) > 1:
            split.append((cls, sorted(leads)))
            continue
        if len(leads) == 1:
            target = next(iter(leads))
            if target != cls:
                f = min(x for x in fs if x in known)
                mapping[cls] = (target, f"{fmt_addr(f)}: {known[f][1]}")
    # the map only grows: a placeholder renamed earlier is gone from src/, but its entry still says
    # what a worker means by it (lint.py, accept.py)
    for cls, (target, why) in read(p).items():
        mapping.setdefault(cls, (target, why))
    # a placeholder spelled with small hex digits names the same address as the capitals (and on a
    # case-blind disk, include/Game/<Class>.h would be one file for both)
    spelled = set()
    for path in (p.src_dir / "Game").glob("*.cpp"):
        spelled |= set(re.findall(r"\b(?:Class|Struct|Object)_[0-9A-Fa-f]{8}\b",
                                  path.read_text(encoding="utf-8", errors="replace")))
    for cls in sorted(spelled):
        upper = cls.split("_")[0] + "_" + cls.split("_")[1].upper()
        if upper != cls and cls not in mapping:
            mapping[cls] = (upper, f"the same address as {upper}, in capitals")
    # what restructure.py found wrong stays out (a class its own base by some unit's declaration)
    for cls in rejected(p):
        mapping.pop(cls, None)
    # a target that is itself mapped: follow the chain
    for cls in list(mapping):
        seen, (target, why) = {cls}, mapping[cls]
        while target in mapping and target not in seen:
            seen.add(target)
            target = mapping[target][0]
        mapping[cls] = (target, why)
    stats = {
        "placeholders with methods": sum(1 for c in methods if PLACEHOLDER.match(c)),
        "mapped": len(mapping),
        "into classes": len({t for t, _ in mapping.values()}),
        "left alone (methods of several classes)": len(split),
        "vtables": len(tables),
    }
    return mapping, stats, split


REJECTED = re.compile(r"^# rejected: (\S+) (\S+) (.*)$")


def read(p: Project) -> Dict[str, Tuple[str, str]]:
    """The map as written: {placeholder: (class, evidence)}."""
    out = {}
    path = p.config_dir / "classmap.txt"
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#"):
                old, new, why = (line.split(None, 2) + [""])[:3]
                out[old] = (new, why.strip())
    return out


def rejected(p: Project) -> Dict[str, Tuple[str, str]]:
    """The entries restructure.py rejected, as `# rejected: <placeholder> <class> <why>` lines: kept out of
    the map (and so out of the gate's [classmap] rule), whatever the evidence says next time."""
    out = {}
    path = p.config_dir / "classmap.txt"
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            m = REJECTED.match(line)
            if m:
                out[m.group(1)] = (m.group(2), m.group(3))
    return out


def with_names(mapping: Dict[str, Tuple[str, str]], names: Dict[str, Tuple[str, str]]) -> Dict[str, Tuple[str, str]]:
    """The map with the names config/<version>/names.txt gives classes (tools/agent/names.py): a named
    placeholder maps to its name, and so does every placeholder the map makes that class."""
    out = {old: ((names[new][0], why) if new in names else (new, why)) for old, (new, why) in mapping.items()}
    for old, (new, why) in names.items():
        out.setdefault(old, (new, f"named: {why}"))
    return out


def write(p: Project, mapping: Dict[str, Tuple[str, str]], rejects: Dict[str, Tuple[str, str]]) -> Path:
    path = p.config_dir / "classmap.txt"
    rows = [f"{old:<24} {new:<32} {why}" for old, (new, why) in sorted(mapping.items()) if old not in rejects]
    rows += [f"# rejected: {old} {new} {why}" for old, (new, why) in sorted(rejects.items())]
    path.write_text(MAP_HEADER + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=("write", "stats"))
    args = ap.parse_args()
    p = Project()
    mapping, stats, split = build(p)
    for k, v in stats.items():
        print(f"{k}: {v}")
    if args.command == "write":
        import names  # names.py imports this module
        path = write(p, with_names(mapping, names.class_names(p)), rejected(p))
        print(f"wrote {path}: {len(mapping)} placeholders")


if __name__ == "__main__":
    main()
